export async function buildSchemaPayload(
  prisma: PrismaClient,
  boardId: string
): Promise<IntelligenceSchema> {
  const scope = await resolveScope(prisma, boardId);
  const sourceTypes: SourceType[] = [];
  if (scope.github.length > 0) sourceTypes.push('github');
  if (scope.jira.length > 0) sourceTypes.push('jira');
  if (scope.ado.length > 0) sourceTypes.push('ado');
  if (scope.gitlab.length > 0) sourceTypes.push('gitlab');

  const tableNames = listTablesForSourceTypes(sourceTypes);
  return {
    tables: tableNames.map((name) => ({
      name,
      columns: [...(TABLE_COLUMNS[name] ?? [])],
    })),
    scope: {
      repos: scope.github,
      jiraProjectKeys: scope.jira,
      adoProjects: scope.ado,
      gitlabProjectPaths: scope.gitlab,
    },
  };
}
